// Windows: dawn.node loads into node.exe and into a program that only
// exports Node-API (as one that embeds Node under another name does).
//
// 1. Its import table: Node-API comes from node.exe, delay-loaded, and nothing
//    is imported from node.exe the ordinary way.
// 2. node.exe loads it.
// 3. A host built here (not node.exe, no Node in it) exports every function
//    dawn.node takes from node.exe, each a stub that reports its name and ends
//    the process. Calling the addon's napi_register_module_v1 makes its first
//    Node-API call, which the delay-load hook must resolve to that host. Without
//    the hook the delay-load helper looks for a node.exe file and the host dies
//    with an exception (or reaches a node.exe on PATH, which is not the host).
//
// Run from an MSVC developer environment (cl.exe), after `npm run build`.
import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { root, target, distDir, run } from './common.mjs'
import { readPe, findDll } from './pe.mjs'

if (!target.startsWith('win32-')) throw new Error(`test-win-host is for win32 targets, not ${target}`)
const addon = path.join(distDir, 'bin', 'dawn.node')

const { imports, delayImports } = readPe(addon)
if (findDll(imports, 'node.exe')) throw new Error('dawn.node imports node.exe directly; it must be delay-loaded (/DELAYLOAD:node.exe)')
const napi = findDll(delayImports, 'node.exe')
if (!napi?.length) throw new Error(`dawn.node does not delay-load node.exe (delay-loaded: ${[...delayImports.keys()].join(', ') || 'nothing'})`)
const bad = napi.filter(n => !/^(napi|node_api)_[a-z0-9_]+$/.test(n))
if (bad.length) throw new Error(`dawn.node takes more than Node-API from node.exe: ${bad.join(', ')}`)
console.log(`dawn.node delay-loads ${napi.length} Node-API functions from node.exe`)

const node = spawnSync(process.execPath, ['-e', `
  const dawn = require(${JSON.stringify(addon)});
  if (typeof dawn.create !== 'function') throw new Error('dawn.node has no create()');
`], { encoding: 'utf8' })
if (node.status !== 0) throw new Error(`node.exe could not load dawn.node:\n${node.stdout}${node.stderr}`)
console.log('node.exe loads dawn.node')

const dir = path.join(root, 'build', 'win-host-test')
fs.rmSync(dir, { recursive: true, force: true })
fs.mkdirSync(dir, { recursive: true })
fs.writeFileSync(path.join(dir, 'host.c'), `// Generated by scripts/test-win-host.mjs
#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <stdio.h>

static void reached(const char* name) {
  printf("first Node-API call resolved to the host: %s\\n", name);
  fflush(stdout);
  TerminateProcess(GetCurrentProcess(), 0);
}
${napi.map(n => `__declspec(dllexport) void* ${n}(void) { reached("${n}"); return 0; }`).join('\n')}

typedef void* (*register_fn)(void* env, void* exports);

int wmain(int argc, wchar_t** argv) {
  if (argc != 2) return 2;
  HMODULE addon = LoadLibraryExW(argv[1], NULL, LOAD_WITH_ALTERED_SEARCH_PATH);
  if (!addon) { printf("LoadLibraryExW failed: %lu\\n", GetLastError()); return 1; }
  register_fn reg = (register_fn)GetProcAddress(addon, "napi_register_module_v1");
  if (!reg) { printf("no napi_register_module_v1\\n"); return 1; }
  reg((void*)1, (void*)2);
  printf("napi_register_module_v1 returned without calling Node-API\\n");
  return 1;
}
`)
run('cl', ['/nologo', '/W3', 'host.c', '/Fe:host.exe'], { cwd: dir })
const host = spawnSync(path.join(dir, 'host.exe'), [addon], { encoding: 'utf8' })
const out = `${host.stdout}${host.stderr}`
if (host.status !== 0 || !out.includes('resolved to the host')) {
  const code = host.status === null ? host.signal : `0x${(host.status >>> 0).toString(16)}`
  throw new Error(`dawn.node did not resolve Node-API from a host that is not node.exe (exit ${code}):\n${out}`)
}
console.log(out.trim())
fs.rmSync(dir, { recursive: true, force: true })
